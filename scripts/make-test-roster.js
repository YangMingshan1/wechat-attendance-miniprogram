#!/usr/bin/env node
/**
 * 生成测试用的学生名单 Excel
 *
 * 用途：验证「学生名单 Excel 批量导入」功能，覆盖正常数据与各类失败场景。
 *
 * 用法（项目根目录）：
 *   node scripts/make-test-roster.js
 *
 * 产出：test-data/学生名单-测试用.xlsx
 * 说明：同时输出 test-data/学生名单-测试用-预期结果.md，列出每一行的预期导入结果，
 *       导入后可比对云函数返回的失败明细是否正确。
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'test-data');
const XLSX = require(path.join(ROOT, '.tools', 'node_modules', 'xlsx'));

/**
 * 数据结构：表头在第 3 行（前两行是说明性文字，用于验证表头探测逻辑）
 * 列顺序刻意打乱并加入无关列，用于验证「按列名识别而非按位置识别」
 */
const rows = [
  // ---- 前两行：说明文字，程序应跳过并继续向下找表头 ----
  ['软件工程专业 2023 级 学生名单（测试数据）', '', '', '', '', ''],
  ['注意：第 3 行才是表头；本表含故意构造的错误行，用于验证导入校验', '', '', '', '', ''],

  // ---- 第 3 行：表头（顺序打乱 + 含无关列）----
  ['序号', '姓名', '备注', '学号', '班级', '辅导员'],

  // ---- 正常数据：10 条，应全部导入成功 ----
  [1, '李小明', '', '20230101001', '软件工程 2301 班', '张老师'],
  [2, '王小红', '', '20230101002', '软件工程 2301 班', '张老师'],
  [3, '赵小刚', '', '20230101003', '软件工程 2301 班', '张老师'],
  [4, '陈小美', '', '20230101004', '软件工程 2302 班', '张老师'],
  [5, '刘小强', '', '20230101005', '软件工程 2302 班', '张老师'],
  [6, '孙小丽', '', '20230101006', '软件工程 2302 班', '张老师'],
  [7, '周小伟', '', '20230201001', '计算机科学 2301 班', '李老师'],
  [8, '吴小芳', '', '20230201002', '计算机科学 2301 班', '李老师'],
  [9, '郑小军', '', '20230201003', '计算机科学 2301 班', '李老师'],
  [10, '冯小燕', '', '20230201004', '计算机科学 2301 班', '李老师'],

  // ---- 错误数据：3 条，应全部被拒并给出具体原因 ----
  // ① 班级为空
  [11, '钱小波', '这条应失败：班级为空', '20230201005', '', '李老师'],
  // ② 姓名为空
  [12, '', '这条应失败：姓名为空', '20230201006', '计算机科学 2302 班', '李老师'],
  // ③ 学号为空
  [13, '蒋小琳', '这条应失败：学号为空', '', '计算机科学 2302 班', '李老师'],

  // ---- 边界数据：学号与上面第 1 条重复 ----
  // 注意：这里必须存成「文本格式」，否则 Excel 会把 11 位数字当数值处理；
  // 而如果写成 "'20230101001"（带前导单引号），xlsx 会把它当真实字符保留下来，
  // 变成另一个长度 12 的学号，达不到"重复"的测试目的。
  [14, '沈小月', '这条应失败：学号与第 4 行重复', '20230101001', '软件工程 2301 班', '张老师'],

  // ---- 空行（应被跳过，不计入总数）----
  ['', '', '', '', '', ''],
  ['', '', '', '', '', ''],

  // ---- 学号写成数字类型（验证数字型学号不会被转成科学计数法）----
  [15, '韩小峰', '学号为数字型，应成功导入', 20230202001, '计算机科学 2302 班', '李老师'],
  [16, '杨小梅', '学号为数字型，应成功导入', 20230202002, '计算机科学 2302 班', '李老师'],
];

/** 第二个工作表：故意用不同表头，用于验证程序只读第一个工作表 */
const sheet2 = [
  ['姓名', '学号', '班级'],
  ['不应被导入', '99999999999', '错误工作表'],
];

function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const wb = XLSX.utils.book_new();

  const ws = XLSX.utils.aoa_to_sheet(rows);

  // 只把「重复学号」那一行的学号设为文本格式，确保它与第 4 行严格相等。
  // 其余行刻意保留数值类型，用于验证数字型学号（易被显示成科学计数法）能正确导入。
  // 注意：这里必须存成「文本格式」，否则 Excel 会把 11 位数字当数值处理；
  // 而如果写成 "'20230101001"（带前导单引号），xlsx 会把它当真实字符保留下来，
  // 变成另一个长度 12 的学号，达不到"重复"的测试目的。
  const dupRows = new Set([17]); // Excel 行号（1 基）
  const range = XLSX.utils.decode_range(ws['!ref']);
  for (let r = range.s.r; r <= range.e.r; r += 1) {
    const excelRow = r + 1;
    if (!dupRows.has(excelRow)) continue;
    const addr = XLSX.utils.encode_cell({ r: r, c: 3 });
    const cell = ws[addr];
    if (cell) {
      cell.t = 's';
      cell.z = '@';
      cell.v = String(cell.v == null ? '' : cell.v);
    }
  }

  ws['!cols'] = [
    { wch: 6 },   // 序号
    { wch: 12 },  // 姓名
    { wch: 34 },  // 备注
    { wch: 16 },  // 学号
    { wch: 22 },  // 班级
    { wch: 10 },  // 辅导员
  ];
  XLSX.utils.book_append_sheet(wb, ws, '学生名单');

  const ws2 = XLSX.utils.aoa_to_sheet(sheet2);
  ws2['!cols'] = [{ wch: 16 }, { wch: 16 }, { wch: 16 }];
  XLSX.utils.book_append_sheet(wb, ws2, '不要导入这个表');

  const file = path.join(OUT_DIR, '学生名单-测试用.xlsx');
  XLSX.writeFile(wb, file);

  console.log('已生成：' + path.relative(ROOT, file));
  console.log('文件大小：' + fs.statSync(file).size + ' 字节');
  console.log('工作表：学生名单（将被导入）、不要导入这个表（用于验证只读第一个表）');
  console.log('\n预期结果见：test-data/学生名单-测试用-预期结果.md');
}

main();
